export const STRINGS: Record<Locale, Dict> = { en, 'zh-HK': zhHK }

/** Look up a UI string in the current locale (falls back to English). */
export function t(key: string, vars?: Record<string, string | number>): string {
  const locale: Locale = state.settings.locale
  let s = STRINGS[locale]?.[key] ?? STRINGS.en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, String(v))
    }
  }
  return s
}

/** Keep <html lang> in sync so screen readers pick the right language. */
export function syncDocumentLang(): void {
  if (typeof document === 'undefined') return
  document.documentElement.lang = state.settings.locale === 'zh-HK' ? 'zh-HK' : 'en'
}
